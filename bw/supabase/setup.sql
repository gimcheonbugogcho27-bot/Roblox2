-- 블록월드 2: 계정별 저장, 스피드 게임 관리자, 전체 명령
create table if not exists public.speed_game_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.speed_game_admins enable row level security;
drop policy if exists "users can read own admin status" on public.speed_game_admins;
create policy "users can read own admin status" on public.speed_game_admins for select to authenticated using (auth.uid() = user_id);


create table if not exists public.speed_game_saves (
  user_id uuid primary key references auth.users(id) on delete cascade,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.speed_game_saves enable row level security;
drop policy if exists "players read own speed save" on public.speed_game_saves;
create policy "players read own speed save" on public.speed_game_saves for select to authenticated using (auth.uid() = user_id);
drop policy if exists "players insert own speed save" on public.speed_game_saves;
create policy "players or admins insert speed save" on public.speed_game_saves for insert to authenticated with check (auth.uid() = user_id or exists(select 1 from public.speed_game_admins a where a.user_id = auth.uid()));
drop policy if exists "players or admins update speed save" on public.speed_game_saves;
create policy "players or admins update speed save" on public.speed_game_saves for update to authenticated using (
  auth.uid() = user_id or exists(select 1 from public.speed_game_admins a where a.user_id = auth.uid())
) with check (
  auth.uid() = user_id or exists(select 1 from public.speed_game_admins a where a.user_id = auth.uid())
);


create table if not exists public.speed_game_commands (
  id bigint generated by default as identity primary key,
  room_code text not null,
  game text not null default 'speed',
  command text not null check (command in ('abuse_start','abuse_stop','reset_stats')),
  payload jsonb not null default '{}'::jsonb,
  target_user_id uuid references auth.users(id) on delete set null,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);
create index if not exists speed_game_commands_room_created_idx on public.speed_game_commands(room_code, created_at desc);
alter table public.speed_game_commands enable row level security;
drop policy if exists "authenticated players read room commands" on public.speed_game_commands;
create policy "authenticated players read room commands" on public.speed_game_commands for select to authenticated using (true);
drop policy if exists "only admins insert commands" on public.speed_game_commands;
create policy "only admins insert commands" on public.speed_game_commands for insert to authenticated with check (
  auth.uid() = created_by and exists(select 1 from public.speed_game_admins a where a.user_id = auth.uid())
);

